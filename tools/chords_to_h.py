#!/usr/bin/env python3
# Makes app/dsp/chords.h from the Plaits Palette chord tables in assets/chords (MIT; see CREDITS.md).
# The voices are cents above the root; the names go to ASCII for the FM-1's fonts.
import json, glob, os
ORDER = ["original", "colour-chords", "disastrous-peace", "tonnetz-walk"]
ASCII = {"♭": "b", "♯": "#", "ø": "o", "°": "dim", "–": "-"}
# short chord symbols that fit a knob card (símbolos cortos)
SHORT = {"Octave": "OCTAVA", "Fifth": "QUINTA", "Minor": "MENOR", "Minor 7th": "MIN7", "Minor 9th": "MIN9",
         "Minor 11th": "MIN11", "Major": "MAYOR", "Major 7th": "MAJ7", "Major 9th": "MAJ9", "Sus4": "SUS4", "6/9": "6/9",
         "6th": "SEXTA", "Spread major 7th": "MAJ7 ABIER", "Dominant 7th": "DOM7", "Dominant 7th flat 9": "DOM7B9",
         "Half diminished": "SEMIDIS", "Fully diminished": "DISM"}
def asc(s):
    s = SHORT.get(s, s)
    for k, v in ASCII.items(): s = s.replace(k, v)
    return s.encode("ascii", "ignore").decode().upper()[:12]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tables = [json.load(open(os.path.join(root, "assets/chords", n + ".plaits-chords.json")))["table"] for n in ORDER]
out = ["// Generated by tools/chords_to_h.py from assets/chords (Plaits Palette chord tables, MIT). Do not edit.",
       "// " + "; ".join(f"{t['name']} by {t['author']}" for t in tables), "#pragma once", "#include <stdint.h>", "",
       "namespace epk {", "", f"constexpr int kChordTables = {len(tables)};",
       f"constexpr int kChordMax = {max(len(t['chords']) for t in tables)};"]
out.append("constexpr int kChordCount[kChordTables] = {" + ", ".join(str(len(t["chords"])) for t in tables) + "};")
out.append("constexpr const char *kChordTableName[kChordTables] = {" + ", ".join('"' + asc(t["name"]) + '"' for t in tables) + "};")
out.append("constexpr int16_t kChordCents[kChordTables][kChordMax][4] = {")
for t in tables:
    rows = [c["voices"] for c in t["chords"]] + [[0, 0, 0, 0]] * (max(len(x["chords"]) for x in tables) - len(t["chords"]))
    out.append("    {" + ", ".join("{" + ", ".join(str(v) for v in r) + "}" for r in rows) + "},")
out.append("};")
out.append("constexpr const char *kChordName[kChordTables][kChordMax] = {")
for t in tables:
    names = ['"' + asc(c["name"]) + '"' for c in t["chords"]] + ['""'] * (max(len(x["chords"]) for x in tables) - len(t["chords"]))
    out.append("    {" + ", ".join(names) + "},")
out += ["};", "", "}  // namespace epk", ""]
open(os.path.join(root, "app/dsp/chords.h"), "w").write("\n".join(out))
print("chords.h:", [len(t["chords"]) for t in tables])
